export const strings: Record<Lang, Strings> = { ar, en }

/**
 * Localized label for a scam category code (e.g. "PRIZE_SCAM").
 * Falls back to the raw code if the backend sends an unknown category.
 */
export function categoryLabel(lang: Lang, category: string): string {
  const dict = strings[lang] as Record<string, string>
  return dict[`cat${category}`] ?? category
}
